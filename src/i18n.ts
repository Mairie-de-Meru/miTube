const DICTS: Record<Lang, Record<Key, string>> = { en, fr }

export type TFn = (key: Key, vars?: Record<string, string | number>) => string

export function makeT(lang: Lang): TFn {
  const dict = DICTS[lang] ?? en
  return (key, vars) => {
    const s = dict[key] ?? en[key]
    return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : s
  }
}

export interface I18n {
  lang: Lang
  t: TFn
}

export const I18nContext = createContext<I18n>({ lang: 'en', t: makeT('en') })
export const useI18n = () => useContext(I18nContext)
export const useT = (): TFn => useContext(I18nContext).t
